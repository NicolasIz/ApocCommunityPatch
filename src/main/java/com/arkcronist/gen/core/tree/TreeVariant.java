package com.arkcronist.gen.core.tree;

/** Shape variants applied on top of a {@link TreeSpecies}. */
public enum TreeVariant {
    /** Ordinary upright tree. */
    NORMAL,
    /** Oversized specimen: taller, thicker trunk, wider crown, buttress roots. */
    GIANT,
    /** Grown at an angle, as if reaching for light or shaped by wind. */
    LEANING,
    /** Toppled trunk lying on the ground with an exposed root plate. */
    FALLEN,
    /** Broken stump left behind, often with a snapped top. */
    STUMP,
    /** Standing dead wood: trunk and bare branches, no leaves. */
    DEAD
}
