package com.arkcronist.gen.bukkit.world;

import com.arkcronist.gen.bukkit.ArkcronistPlugin;
import net.kyori.adventure.util.TriState;
import org.bukkit.World;
import org.bukkit.WorldCreator;

import java.util.ArrayDeque;
import java.util.Deque;
import java.util.logging.Level;

/**
 * Gives each generated world a Nether and an End of its own.
 *
 * <p>A server with a BASE world and an INSANE world had one Nether between them - the server's - and
 * one End. Walk through a portal in either and you came out in the same place, which makes the two
 * presets share the half of the game that is not the overworld. These are separate worlds instead,
 * named by the server's own convention so they sit on disk where anybody would look for them.</p>
 *
 * <p><b>They are generated by the game, not by this plugin.</b> That is a decision and not a
 * shortcut: the Nether is 128 blocks tall under a bedrock roof with no sky and no sea, and the End is
 * void with floating islands and a dragon fight wired into its structures. This generator's engine is
 * an overworld engine - continents, oceans, a sea level, mountains - and none of that transfers.
 * Handing those two dimensions to the game gives a Nether and an End that work properly, including
 * the dragon, and leaves the door open to generating them ourselves later without changing anything
 * a player would notice about how they are reached.</p>
 */
public final class DimensionManager {

    private final ArkcronistPlugin plugin;

    public DimensionManager(ArkcronistPlugin plugin) {
        this.plugin = plugin;
    }

    /**
     * Makes sure this world's Nether and End exist.
     *
     * <p>Does nothing when they already do, whoever made them: a server already running
     * Multiverse with its own {@code insane_nether} keeps that one. This adds the worlds that are
     * missing, it does not take over the ones that are there.</p>
     *
     * <p>One world per tick, never two. Creating a world is a blocking call that generates the new
     * world's spawn region, and the tick that does it is as long as that takes. Paper's watchdog
     * measures exactly that - how long a single tick has been running - so two creations sharing a
     * tick add up against one limit while two creations a tick apart are measured separately. Today
     * the companions are vanilla and cost a few hundred milliseconds together, so this changes
     * nothing anybody can see; it is here so that the day one of them is generated by this plugin's
     * own engine, at seconds rather than milliseconds, it does not become a server hang.</p>
     */
    public void ensureCompanions(World base) {
        if (!plugin.arkConfig().ownDimensions()) {
            return;
        }
        if (!DimensionLinks.wantsCompanions(base.getEnvironment())) {
            return;
        }
        Deque<Runnable> pending = new ArrayDeque<>(2);
        if (plugin.arkConfig().ownNether()) {
            pending.add(() -> ensure(
                    DimensionLinks.netherOf(base.getName(), plugin.arkConfig().netherSuffix()),
                    World.Environment.NETHER,
                    DimensionLinks.seedFor(base.getSeed(), true), base.getName()));
        }
        if (plugin.arkConfig().ownEnd()) {
            pending.add(() -> ensure(
                    DimensionLinks.endOf(base.getName(), plugin.arkConfig().endSuffix()),
                    World.Environment.THE_END,
                    DimensionLinks.seedFor(base.getSeed(), false), base.getName()));
        }
        drain(pending);
    }

    /** Runs the head of the queue now and hands the rest to the next tick. */
    private void drain(Deque<Runnable> pending) {
        Runnable next = pending.poll();
        if (next == null) {
            return;
        }
        next.run();
        if (!pending.isEmpty()) {
            plugin.getServer().getScheduler().runTask(plugin, () -> drain(pending));
        }
    }

    private void ensure(String name, World.Environment environment, long seed, String belongsTo) {
        if (plugin.getServer().getWorld(name) != null) {
            return;
        }
        // "Opening" rather than "creating", because both happen here and an admin reading the log
        // should not be told a world is being created every restart. A world a plugin made is not
        // remembered by the server across restarts, so after the first time this call finds the
        // folder on disk and loads it - same method, same log line, entirely different event.
        boolean fresh = !new java.io.File(plugin.getServer().getWorldContainer(), name).isDirectory();
        plugin.getLogger().info((fresh ? "Creating " : "Opening ") + environment + " world '" + name
                + "' for '" + belongsTo + "'" + (fresh ? " (seed " + seed + ")" : "")
                + ". This loads its spawn chunks and will pause the server briefly.");
        long started = System.nanoTime();
        try {
            World created = new WorldCreator(name)
                    .environment(environment)
                    .seed(seed)
                    // A companion is somewhere players travel to, not somewhere the server has to be
                    // ready for at all times. Held spawn chunks are a permanent cost - a few hundred
                    // chunks of blocks, entities and ticking, per world, for as long as the server is
                    // up - and a server running three presets has six of these. They load when
                    // somebody arrives, which is the moment they are worth loading.
                    .keepSpawnLoaded(TriState.FALSE)
                    .createWorld();
            if (created == null) {
                plugin.getLogger().warning("The server would not create '" + name
                        + "'. Portals from '" + belongsTo + "' will keep going wherever they went "
                        + "before.");
                return;
            }
            // The time is logged because this is the one place in the plugin that deliberately blocks
            // the main thread, so when a watchdog dump lands on this frame the log next to it already
            // says whether this call was the stall or merely what the server happened to be doing
            // when the dump was taken.
            plugin.getLogger().info("'" + name + "' is ready ("
                    + ((System.nanoTime() - started) / 1_000_000L) + " ms).");
        } catch (RuntimeException exception) {
            // A world manager that objects, a name the server will not take, a disk that is full:
            // none of them is worth taking the plugin down for. The overworld still generates.
            plugin.getLogger().log(Level.WARNING, "Could not create '" + name + "' for '" + belongsTo
                    + "'; its portals stay as they were.", exception);
        }
    }
}
