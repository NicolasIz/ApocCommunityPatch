package com.arkcronist.gen.bukkit.mobs;

import com.arkcronist.gen.bukkit.ArkWorld;
import com.arkcronist.gen.bukkit.ArkcronistPlugin;
import org.bukkit.World;

/**
 * Which worlds the custom hostile mobs apply to, and under which preset.
 *
 * <p>Two different questions used to be answered by the same line of code in two places: "did this
 * generator make this world" and "should the custom mobs be here". They were the same answer for as
 * long as the only way to get Arkcronist mobs was to let Arkcronist build the world.</p>
 *
 * <p>They are not the same question. A server can want a world generated by something else
 * entirely - a terrain datapack, another generator plugin, a map somebody built by hand - and still
 * want the goblins and the volcanic skeletons in it. The terrain and the structures cannot follow
 * into such a world, because both are built from this generator's own idea of where the ground is,
 * but the mobs have no such tie: they are placed around players, on ground that is already there.
 * So a world can be named in config and adopted, and the preset named beside it decides which mob
 * table applies exactly as a generated world's own preset does.</p>
 */
final class MobWorlds {

    private MobWorlds() {
    }

    /**
     * The preset name to treat this world as, or null when it is neither generated nor adopted.
     */
    static String presetOf(ArkcronistPlugin plugin, World world) {
        ArkWorld ark = plugin.worlds().find(world.getName());
        if (ark != null) {
            return ark.preset().name();
        }
        return plugin.arkConfig().adoptedPreset(world.getName());
    }

    /** Whether the custom hostile mobs belong in this world at all. */
    static boolean applies(ArkcronistPlugin plugin, World world) {
        String preset = presetOf(plugin, world);
        return preset != null && plugin.arkConfig().hostileMobPresets().contains(preset);
    }
}
